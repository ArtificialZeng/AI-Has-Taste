#!/usr/bin/env python3
"""Exact cross-checks for the Builder's double-leafy-extension theorem.

This is a diagnostic, not the proof.  It compares two independent exact
evaluators on every labelled base tree generated by Prüfer words:

1. rooted-tree dynamic programming on the expanded tree; and
2. brute-force independent-set counts on the base tree followed by the
   claimed gamma-basis formula.

Only Python integers are used.  There is no random seed.
"""

from __future__ import annotations

import argparse
import hashlib
import heapq
import itertools
import json
import math
import platform
from pathlib import Path


def poly_add(p: list[int], q: list[int]) -> list[int]:
    out = [0] * max(len(p), len(q))
    for i, value in enumerate(p):
        out[i] += value
    for i, value in enumerate(q):
        out[i] += value
    while len(out) > 1 and out[-1] == 0:
        out.pop()
    return out


def poly_mul(p: list[int], q: list[int]) -> list[int]:
    out = [0] * (len(p) + len(q) - 1)
    for i, left in enumerate(p):
        for j, right in enumerate(q):
            out[i + j] += left * right
    while len(out) > 1 and out[-1] == 0:
        out.pop()
    return out


def adjacency(n: int, edges: list[tuple[int, int]]) -> list[list[int]]:
    adj = [[] for _ in range(n)]
    for u, v in edges:
        if not (0 <= u < v < n):
            raise ValueError(f"edge must satisfy 0 <= u < v < n: {(u, v)}")
        adj[u].append(v)
        adj[v].append(u)
    if n < 1 or len(edges) != n - 1:
        raise ValueError("input is not a nonempty tree")
    seen = {0}
    stack = [0]
    while stack:
        u = stack.pop()
        for v in adj[u]:
            if v not in seen:
                seen.add(v)
                stack.append(v)
    if len(seen) != n:
        raise ValueError("input is disconnected")
    return adj


def tree_dp_polynomial(n: int, edges: list[tuple[int, int]]) -> list[int]:
    adj = adjacency(n, edges)

    def visit(u: int, parent: int) -> tuple[list[int], list[int]]:
        # A excludes u; B includes u.
        a = [1]
        b = [0, 1]
        for v in adj[u]:
            if v == parent:
                continue
            child_a, child_b = visit(v, u)
            a = poly_mul(a, poly_add(child_a, child_b))
            b = poly_mul(b, child_a)
        return a, b

    root_a, root_b = visit(0, -1)
    return poly_add(root_a, root_b)


def brute_independence_polynomial(
    n: int, edges: list[tuple[int, int]]
) -> list[int]:
    counts = [0] * (n + 1)
    edge_masks = [(1 << u) | (1 << v) for u, v in edges]
    for mask in range(1 << n):
        if all(mask & edge_mask != edge_mask for edge_mask in edge_masks):
            counts[mask.bit_count()] += 1
    while len(counts) > 1 and counts[-1] == 0:
        counts.pop()
    return counts


def double_leafy_extension(
    n: int, edges: list[tuple[int, int]]
) -> tuple[int, list[tuple[int, int]]]:
    expanded = list(edges)
    for v in range(n):
        expanded.append((v, n + 2 * v))
        expanded.append((v, n + 2 * v + 1))
    return 3 * n, [tuple(sorted(edge)) for edge in expanded]


def gamma_formula(base_counts: list[int], n: int) -> list[int]:
    # sum_j i_j(H) x^j (1+x)^(2n-2j)
    out = [0] * (2 * n + 1)
    for j, gamma_j in enumerate(base_counts):
        for r in range(2 * (n - j) + 1):
            out[j + r] += gamma_j * math.comb(2 * (n - j), r)
    return out


def prufer_edges(n: int, word: tuple[int, ...]) -> list[tuple[int, int]]:
    if n == 1:
        if word:
            raise ValueError("the one-vertex tree has an empty Prüfer word")
        return []
    if len(word) != n - 2:
        raise ValueError("wrong Prüfer word length")
    degree = [1] * n
    for v in word:
        degree[v] += 1
    leaves = [v for v, d in enumerate(degree) if d == 1]
    heapq.heapify(leaves)
    edges: list[tuple[int, int]] = []
    for v in word:
        leaf = heapq.heappop(leaves)
        edges.append(tuple(sorted((leaf, v))))
        degree[leaf] -= 1
        degree[v] -= 1
        if degree[v] == 1:
            heapq.heappush(leaves, v)
    u = heapq.heappop(leaves)
    v = heapq.heappop(leaves)
    edges.append(tuple(sorted((u, v))))
    return edges


def labelled_trees(n: int):
    if n == 1:
        yield []
        return
    for word in itertools.product(range(n), repeat=n - 2):
        yield prufer_edges(n, word)


def verify_one(n: int, edges: list[tuple[int, int]]) -> None:
    base_brute = brute_independence_polynomial(n, edges)
    base_dp = tree_dp_polynomial(n, edges)
    if base_brute != base_dp:
        raise AssertionError(("base evaluators disagree", n, edges, base_brute, base_dp))

    expanded_n, expanded_edges = double_leafy_extension(n, edges)
    expanded_dp = tree_dp_polynomial(expanded_n, expanded_edges)
    predicted = gamma_formula(base_brute, n)
    if expanded_dp != predicted:
        raise AssertionError(
            ("gamma identity failed", n, edges, expanded_dp, predicted)
        )
    if len(expanded_dp) != 2 * n + 1:
        raise AssertionError(("wrong independence number", n, edges, expanded_dp))
    if expanded_dp != list(reversed(expanded_dp)):
        raise AssertionError(("not symmetric", n, edges, expanded_dp))
    if not all(expanded_dp[k] < expanded_dp[k + 1] for k in range(n)):
        raise AssertionError(("not strictly increasing to center", n, edges, expanded_dp))
    if not all(expanded_dp[k] > expanded_dp[k + 1] for k in range(n, 2 * n)):
        raise AssertionError(("not strictly decreasing from center", n, edges, expanded_dp))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--max-n", type=int, default=6)
    args = parser.parse_args()
    if not (1 <= args.max_n <= 8):
        raise SystemExit("--max-n must lie in [1,8]")

    tested = 0
    by_order: dict[int, int] = {}
    for n in range(1, args.max_n + 1):
        count = 0
        for edges in labelled_trees(n):
            verify_one(n, edges)
            count += 1
        expected = 1 if n == 1 else n ** (n - 2)
        if count != expected:
            raise AssertionError(("Cayley count mismatch", n, count, expected))
        by_order[n] = count
        tested += count

    code_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()
    print(
        json.dumps(
            {
                "status": "PASS",
                "arithmetic": "exact Python integers",
                "python": platform.python_version(),
                "max_base_order": args.max_n,
                "labelled_trees_by_order": by_order,
                "total_labelled_trees": tested,
                "code_sha256": code_hash,
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
