#!/usr/bin/env python3
"""Exact scan of the connected eight-vertex layer of Conjecture 7.3.

Graphs are generated by extending every seven-vertex graph in NetworkX's
graph atlas by one vertex, then deduplicated by exact graph isomorphism.  All
symmetric functions are represented over Z in the complete-homogeneous basis.
The conversion h_mu -> sum_lambda K_{lambda,mu} s_lambda is computed exactly
by the horizontal-strip (Pieri) rule.

The program deliberately uses no floating-point arithmetic.  Its JSONL record
contains one line per graph, enough to replay the representative list and to
compare every Schur coefficient through deterministic hashes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import tempfile
import time
from collections import defaultdict
from functools import lru_cache

import networkx as nx


N = 8
ONE = {(): 1}


@lru_cache(maxsize=None)
def integer_partitions(total: int, maximum: int | None = None):
    """Partitions as weakly decreasing tuples, in reverse lexicographic order."""
    if total == 0:
        return ((),)
    if maximum is None or maximum > total:
        maximum = total
    ans = []
    for first in range(maximum, 0, -1):
        for tail in integer_partitions(total - first, min(first, total - first)):
            ans.append((first,) + tail)
    return tuple(ans)


def horizontal_strip(inner, outer) -> bool:
    """Return whether outer/inner is a horizontal strip (assuming containment)."""
    width = max(len(inner), len(outer))
    a = inner + (0,) * (width - len(inner))
    b = outer + (0,) * (width - len(outer))
    if any(a[i] > b[i] for i in range(width)):
        return False
    # Interlacing b_1 >= a_1 >= b_2 >= a_2 >= ... is equivalent to
    # having at most one new cell in every column.
    return all(a[i] >= b[i + 1] for i in range(width - 1))


@lru_cache(maxsize=None)
def h_basis_to_schur(mu):
    """Exact Schur expansion of h_mu, via successive horizontal strips."""
    expansion = {(): 1}
    degree = 0
    for strip_size in mu:
        degree += strip_size
        new = defaultdict(int)
        for outer in integer_partitions(degree):
            for inner, coefficient in expansion.items():
                if horizontal_strip(inner, outer):
                    new[outer] += coefficient
        expansion = dict(new)
    return expansion


def add_scaled(target, source, scale=1):
    for basis, coefficient in source.items():
        value = target.get(basis, 0) + scale * coefficient
        if value:
            target[basis] = value
        elif basis in target:
            del target[basis]


def multiply(left, right):
    """Multiply two symmetric functions represented in the h basis."""
    if not left or not right:
        return {}
    ans = defaultdict(int)
    for a, ca in left.items():
        for b, cb in right.items():
            ans[tuple(sorted(a + b, reverse=True))] += ca * cb
    return {basis: coefficient for basis, coefficient in ans.items() if coefficient}


def append_h(poly, degree):
    """Multiply by the single complete function h_degree."""
    if degree == 0:
        return dict(poly)
    ans = defaultdict(int)
    for basis, coefficient in poly.items():
        ans[tuple(sorted(basis + (degree,), reverse=True))] += coefficient
    return dict(ans)


def to_schur(poly):
    ans = defaultdict(int)
    for mu, coefficient in poly.items():
        for lam, kostka in h_basis_to_schur(mu).items():
            ans[lam] += coefficient * kostka
    return {lam: coefficient for lam, coefficient in ans.items() if coefficient}


def adjacency_masks(graph):
    return tuple(sum(1 << w for w in graph.neighbors(v)) for v in range(N))


def connected_subsets(adj):
    """Boolean connectivity table for all vertex subsets (singletons included)."""
    conn = [False] * (1 << N)
    for subset in range(1, 1 << N):
        reached = subset & -subset
        while True:
            neighbors = 0
            frontier = reached
            while frontier:
                bit = frontier & -frontier
                frontier ^= bit
                neighbors |= adj[bit.bit_length() - 1]
            grown = reached | (neighbors & subset)
            if grown == reached:
                break
            reached = grown
        conn[subset] = reached == subset
    return conn


def homogeneous_parts(graph):
    """Return F_d=Psi_G|degree d in the h basis, for d=0,...,7.

    For every S, A[S][k] is the sum over connected-block partitions of S
    into k blocks of the product of their Mobius symmetric functions.  Anchoring
    each partition at its least vertex counts it once.  Formula (5.3) gives the
    one-block function M_{G|S} from the already computed k>=2 entries.
    """
    adj = adjacency_masks(graph)
    conn = connected_subsets(adj)
    table = [[{} for _ in range(N + 1)] for _ in range(1 << N)]
    mobius = [{} for _ in range(1 << N)]
    table[0][0] = ONE

    subsets = sorted(range(1, 1 << N), key=int.bit_count)
    for subset in subsets:
        anchor = subset & -subset
        block = (subset - 1) & subset
        while block:
            if block & anchor and conn[block]:
                rest = subset ^ block
                left = mobius[block]
                if left:
                    for rest_count in range(N):
                        right = table[rest][rest_count]
                        if right:
                            add_scaled(
                                table[subset][rest_count + 1],
                                multiply(left, right),
                            )
            block = (block - 1) & subset

        if conn[subset]:
            if subset.bit_count() == 1:
                current = dict(ONE)
            else:
                current = {}
                for count in range(2, subset.bit_count() + 1):
                    add_scaled(current, append_h(table[subset][count], count - 1), -1)
            mobius[subset] = current
            table[subset][1] = current

    full = (1 << N) - 1
    return [table[full][N - degree] for degree in range(N)]


def graph_key(graph):
    """Fast isomorphism invariant; equality is followed by exact matching."""
    degrees = tuple(sorted(dict(graph.degree()).values()))
    triangles = tuple(sorted(nx.triangles(graph).values()))
    wl = nx.weisfeiler_lehman_graph_hash(graph, iterations=4, digest_size=16)
    return degrees, triangles, wl


def graph_representatives():
    """Generate exactly one representative of every connected order-8 graph."""
    bases = [graph for graph in nx.graph_atlas_g() if len(graph) == N - 1]
    buckets = defaultdict(list)
    representatives = []
    connected_extensions = 0
    for base in bases:
        for neighborhood in range(1, 1 << (N - 1)):
            graph = base.copy()
            graph.add_node(N - 1)
            graph.add_edges_from(
                (N - 1, vertex)
                for vertex in range(N - 1)
                if neighborhood & (1 << vertex)
            )
            if not nx.is_connected(graph):
                continue
            connected_extensions += 1
            key = graph_key(graph)
            if any(nx.is_isomorphic(graph, old) for old in buckets[key]):
                continue
            buckets[key].append(graph)
            representatives.append(graph)
    return representatives, len(bases), connected_extensions, len(buckets)


def encoded_coefficients(coefficients):
    return [[list(partition), coefficients[partition]] for partition in sorted(coefficients)]


def canonical_json(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def coefficient_digest(coefficients):
    data = canonical_json(encoded_coefficients(coefficients)).encode()
    return hashlib.sha256(data).hexdigest()


def scan_graph(graph):
    f = homogeneous_parts(graph)
    degree_records = []
    witness = None
    for degree in range(1, N):
        ell = multiply(f[degree], f[degree])
        if degree + 1 < N:
            add_scaled(ell, multiply(f[degree - 1], f[degree + 1]), -1)
        schur = to_schur(ell)
        all_partitions = integer_partitions(2 * degree)
        values = {partition: schur.get(partition, 0) for partition in all_partitions}
        minimum = min(values.values())
        minimizers = [partition for partition in all_partitions if values[partition] == minimum]
        degree_records.append(
            {
                "d": degree,
                "coefficient_count": len(all_partitions),
                "minimum": minimum,
                "first_minimizer": list(minimizers[0]),
                "schur_sha256": coefficient_digest(values),
            }
        )
        if minimum < 0 and witness is None:
            partition = minimizers[0]
            witness = {
                "degree": degree,
                "partition": list(partition),
                "coefficient": values[partition],
                "F_previous_h": encoded_coefficients(f[degree - 1]),
                "F_degree_h": encoded_coefficients(f[degree]),
                "F_next_h": encoded_coefficients(f[degree + 1] if degree + 1 < N else {}),
                "L_schur": encoded_coefficients(values),
            }
            break
    return degree_records, witness


def write_summary(path, summary):
    directory = os.path.dirname(path) or "."
    fd, temporary = tempfile.mkstemp(prefix="eight-vertex-summary-", dir=directory, text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(json.dumps(summary, indent=2, sort_keys=True))
            stream.write("\n")
        os.replace(temporary, path)
    except BaseException:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--records", default="evidence/eight_vertex_records.jsonl")
    parser.add_argument("--summary", default="evidence/eight_vertex_summary.json")
    parser.add_argument("--limit", type=int, default=0, help="debug: scan only this many classes")
    parser.add_argument("--progress-every", type=int, default=250)
    args = parser.parse_args()

    started = time.time()
    reps, atlas_bases, connected_extensions, invariant_buckets = graph_representatives()
    reps.sort(key=lambda graph: nx.to_graph6_bytes(graph, header=False).strip())
    if args.limit:
        reps = reps[: args.limit]

    record_hasher = hashlib.sha256()
    class_hasher = hashlib.sha256()
    chordal_count = 0
    total_coefficients = 0
    global_minimum = None
    negative = None

    with open(args.records, "w", encoding="utf-8") as stream:
        for index, graph in enumerate(reps, 1):
            graph6 = nx.to_graph6_bytes(graph, header=False).strip().decode("ascii")
            class_hasher.update((graph6 + "\n").encode())
            chordal = nx.is_chordal(graph)
            chordal_count += int(chordal)
            degree_records, witness = scan_graph(graph)
            total_coefficients += sum(item["coefficient_count"] for item in degree_records)
            local_minimum = min(item["minimum"] for item in degree_records)
            global_minimum = local_minimum if global_minimum is None else min(global_minimum, local_minimum)
            record = {
                "index": index,
                "graph6": graph6,
                "edges": graph.number_of_edges(),
                "chordal": chordal,
                "degrees": degree_records,
            }
            if witness is not None:
                record["negative_witness"] = witness
            line = canonical_json(record) + "\n"
            stream.write(line)
            stream.flush()
            record_hasher.update(line.encode())
            if witness is not None:
                negative = {"graph_record": record, "scanned_classes": index}
                break
            if args.progress_every and index % args.progress_every == 0:
                partial = {
                    "status": "partial",
                    "scanned_classes": index,
                    "enumerated_classes": len(reps),
                    "global_minimum": global_minimum,
                    "record_prefix_sha256": record_hasher.hexdigest(),
                    "elapsed_seconds": round(time.time() - started, 3),
                }
                write_summary(args.summary, partial)
                print(canonical_json(partial), flush=True)

    summary = {
        "status": "negative-certificate" if negative else "complete",
        "networkx_version": nx.__version__,
        "atlas_seven_vertex_bases": atlas_bases,
        "connected_extensions_tested": connected_extensions,
        "isomorphism_invariant_buckets": invariant_buckets,
        "enumerated_connected_classes": len(reps),
        "scanned_classes": negative["scanned_classes"] if negative else len(reps),
        "chordal_classes_scanned": chordal_count,
        "nonchordal_classes_scanned": (negative["scanned_classes"] if negative else len(reps)) - chordal_count,
        "degrees_per_complete_class": list(range(1, N)),
        "schur_coefficients_tested": total_coefficients,
        "global_minimum": global_minimum,
        "representative_graph6_sha256": class_hasher.hexdigest(),
        "records_sha256": record_hasher.hexdigest(),
        "exact_arithmetic": "integers in h and Schur bases; no floating point",
        "elapsed_seconds": round(time.time() - started, 3),
    }
    if negative:
        summary["negative_certificate"] = negative
    write_summary(args.summary, summary)
    print(canonical_json(summary))


if __name__ == "__main__":
    main()
